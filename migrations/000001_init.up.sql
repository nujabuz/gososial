CREATE SEQUENCE IF NOT EXISTS users_id_seq
AS BIGINT
INCREMENT BY 1
START 1001
NO CYCLE;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT NOT NULL PRIMARY KEY DEFAULT NEXTVAL('users_id_seq'),
  username VARCHAR(16) NOT NULL UNIQUE,
  password VARCHAR(24) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER SEQUENCE IF EXISTS users_id_seq OWNED BY users.id;

CREATE SEQUENCE IF NOT EXISTS posts_id_seq
AS BIGINT
INCREMENT BY 1
START 1001
NO CYCLE;

CREATE TABLE IF NOT EXISTS posts (
  id BIGINT NOT NULL PRIMARY KEY DEFAULT NEXTVAL('posts_id_seq'),
  user_id BIGINT NOT NULL,
  body TEXT NOT NULL,
  created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER SEQUENCE IF EXISTS posts_id_seq OWNED BY posts.id;

CREATE SEQUENCE IF NOT EXISTS like_posts_id_seq
AS BIGINT
INCREMENT BY 1
START 1
NO CYCLE;

CREATE TABLE IF NOT EXISTS like_posts (
  id BIGINT NOT NULL PRIMARY KEY DEFAULT NEXTVAL('like_posts_id_seq'),
  post_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE(user_id, post_id),
  CONSTRAINT fk_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_post FOREIGN KEY (post_id) REFERENCES posts(id) ON DELETE CASCADE
);

ALTER SEQUENCE IF EXISTS like_posts_id_seq OWNED BY like_posts.id;

